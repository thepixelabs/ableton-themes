function spec(o) {
  return {
    id: o.id, name: o.name, family: o.family,
    mode: o.mode || 'dark',
    bgHue: o.bgHue, bgChroma: o.bgChroma,
    depth: o.depth || 0,
    contrast: o.contrast === undefined ? 0.1 : o.contrast,
    accent: o.accent, accent2: o.accent2,
    chroma: o.chroma === undefined ? 1 : o.chroma,
    rehue: !!o.rehue, hueShift: o.hueShift || 0,
    clips: o.clips || { origin: 20, spread: 340, chroma: 0.13, lightness: 0.70 },
    overrides: o.overrides || {}
  };
}

